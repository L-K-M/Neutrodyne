private const val SYMBOL_VIEWPORT: Float = 960f

// Material Symbols draw into a 960×960 viewBox that starts at y = -960.
private fun symbolIcon(pathData: String): ImageVector =
    ImageVector
        .Builder(
            name = "NdSymbol",
            defaultWidth = 24.dp,
            defaultHeight = 24.dp,
            viewportWidth = SYMBOL_VIEWPORT,
            viewportHeight = SYMBOL_VIEWPORT,
        ).group(translationY = SYMBOL_VIEWPORT) {
            addPath(
                pathData = addPathNodes(pathData),
                fill = SolidColor(Color.Black),
            )
        }.build()
